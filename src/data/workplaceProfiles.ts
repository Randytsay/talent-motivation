export interface WorkplaceDiagnosis {
  thriving: string;
  friction: string;
  guidance: string;
  dynamicNote?: string;
}

export function generateWorkplaceDiagnosis(
  lifePathNumber: number,
  activeLineKeys: string[] = []
): WorkplaceDiagnosis {
  const base = WORKPLACE_BASE_PROFILES[lifePathNumber] ?? WORKPLACE_BASE_PROFILES[1];
  let dynamicFrictionAddition = '';
  let dynamicThrivingAddition = '';

  if (activeLineKeys.includes('48')) {
    dynamicThrivingAddition = ' 同時，你具備看透全局與推進排程的策略直覺，善於為複雜任務規劃出最省力的路線。';
    dynamicFrictionAddition = ' 特別是當工作缺乏明確策略、團隊毫無章法地盲目救火時，你的疲憊感會成倍放大。';
  } else if (activeLineKeys.includes('159')) {
    dynamicThrivingAddition = ' 同時，你自帶極高的目標推動力，看到進度一項項被打勾完成，會帶給你極大的爽快感。';
    dynamicFrictionAddition = ' 特別是遇到團隊同仁推拖拉、效率低落卻無人擔責時，你心裡的急躁與火氣會瞬間升溫。';
  } else if (activeLineKeys.includes('258') || activeLineKeys.includes('357')) {
    dynamicThrivingAddition = ' 同時，你具備極佳的破冰親和力與溝通直覺，在需要跨界協調或帶動氛圍時往往能發揮奇效。';
    dynamicFrictionAddition = ' 特別是如果被長期孤立在冷冰冰的封閉環境、缺乏有溫度的人際交流，你的活力會迅速枯萎。';
  } else if (activeLineKeys.includes('147')) {
    dynamicThrivingAddition = ' 同時，你具備扎實落地、把事情做到位的極高可靠度，用實際產出說話。';
    dynamicFrictionAddition = ' 特別反感高層只畫大餅卻拿不出具體預算與資源支援的空談，那會讓你感到極不安全。';
  } else if (activeLineKeys.includes('369')) {
    dynamicThrivingAddition = ' 同時，你擅長把專業艱深的知識轉化為容易理解的創意或生動表達。';
    dynamicFrictionAddition = ' 特別受不了死記硬背或完全不允許任何創新的僵化指令，那會扼殺你的靈感。';
  }

  return {
    thriving: `${base.thriving}${dynamicThrivingAddition}`,
    friction: `${base.friction}${dynamicFrictionAddition}`,
    guidance: base.guidance,
  };
}
