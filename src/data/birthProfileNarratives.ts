export function getProfileTension(outer: number, inner: number): string {
  if (outer === inner) {
    return `這兩個角度都指向「${outer} 號」的主題。可以想想：在生活中，哪些時候你能同時保有外在的做法與內在重視的條件？`;
  }
  return '一個角度談到你如何面對外界，另一個談到你可能重視的內在條件。可以想想：這兩者在最近的生活裡如何一起出現？';
}
