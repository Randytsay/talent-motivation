export function getProfileTension(outer: number, inner: number): string {
  if (outer === inner) {
    return `你的外在表現與內在渴望高度一致（都是 ${outer} 號能量），在人前人後非常真實自然、表裡如一；只要方向對了，就能全然釋放力量！`;
  }
  const outerDesc = OUTER_NARRATIVES[outer] ?? '展現出獨特的個人氣質';
  const innerDesc = INNER_NARRATIVES[inner] ?? '保有自己的內在追求';
  return `外在你看起來「${outerDesc}」，但唯有你自己知道，私底下的你其實「${innerDesc}」——這種外在擔當與內在心聲的反差，正是你最真實也最值得被理解的特質。`;
}
